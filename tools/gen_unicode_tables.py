#!/usr/bin/env python3
"""Generate src/tokenizer/unicode_tables.inc: code point ranges for the regex classes the
byte-level BPE pretokenizers use (\\p{L}, \\p{N}, \\s).

Usage:
    python tools/gen_unicode_tables.py > src/tokenizer/unicode_tables.inc

The output is checked in; rerun only to move to a newer Unicode version.
"""
import sys
import unicodedata

# Unicode White_Space property (what \s matches in the Rust/Oniguruma regexes HF uses).
WHITE_SPACE = [(0x09, 0x0D), (0x20, 0x20), (0x85, 0x85), (0xA0, 0xA0), (0x1680, 0x1680),
               (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F),
               (0x3000, 0x3000)]


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in range(0x110000):
        if pred(cp):
            if out and out[-1][1] == cp - 1:
                out[-1] = (out[-1][0], cp)
            else:
                out.append((cp, cp))
    return out


def emit(name: str, rs: list[tuple[int, int]]) -> None:
    print(f"// {len(rs)} ranges")
    print(f"constexpr CodepointRange {name}[] = {{")
    for i in range(0, len(rs), 4):
        print("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in rs[i:i + 4]))
    print("};\n")


def main() -> None:
    cat = lambda cp: unicodedata.category(chr(cp))
    print(f"// Generated by tools/gen_unicode_tables.py from Unicode {unicodedata.unidata_version}.")
    print("// Do not edit. Inclusive [first, last] code point ranges, sorted.\n")
    emit("kLetterRanges", ranges(lambda cp: cat(cp)[0] == "L"))
    emit("kNumberRanges", ranges(lambda cp: cat(cp)[0] == "N"))
    emit("kWhitespaceRanges", WHITE_SPACE)


if __name__ == "__main__":
    sys.exit(main())
